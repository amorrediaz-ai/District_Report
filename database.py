"""PostgreSQL connection and schema shared by the website and SQLite importer."""
from __future__ import annotations

import os

import psycopg
from psycopg.conninfo import conninfo_to_dict
from psycopg.rows import dict_row

SCHEMA_LOCK = 2622001


def connect_db() -> psycopg.Connection:
    url = os.environ.get("DATABASE_URL", "").strip()
    if not url.startswith(("postgres://", "postgresql://")):
        raise RuntimeError("Укажите PostgreSQL DATABASE_URL в переменных окружения.")
    settings = conninfo_to_dict(url)
    host = settings.get("host", "")
    local = not host or host in {"localhost", "127.0.0.1", "::1"} or host.startswith("/")
    # Render accepts sslmode=require, including on its internal connection URL.
    settings.setdefault("sslmode", "disable" if local else "require")
    settings.setdefault("connect_timeout", "10")
    conn = psycopg.connect(**settings, row_factory=dict_row, autocommit=True)
    conn.execute("SET TIME ZONE 'UTC'")
    return conn


def initialize_schema(conn: psycopg.Connection) -> None:
    """Call inside conn.transaction(); safe when several workers start together."""
    conn.execute("SELECT pg_advisory_xact_lock(%s)", (SCHEMA_LOCK,))
    for statement in SCHEMA:
        conn.execute(statement)


SCHEMA = (
    """CREATE TABLE IF NOT EXISTS users (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name TEXT NOT NULL,
        email TEXT NOT NULL UNIQUE,
        password_hash TEXT NOT NULL,
        is_admin BOOLEAN NOT NULL DEFAULT FALSE,
        created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    )""",
    "CREATE UNIQUE INDEX IF NOT EXISTS idx_users_email_lower ON users (lower(email))",
    """CREATE TABLE IF NOT EXISTS report (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        title TEXT,
        location TEXT,
        description TEXT,
        user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
        counter_likes INTEGER NOT NULL DEFAULT 0 CHECK (counter_likes >= 0),
        status TEXT DEFAULT 'На рассмотрении',
        type TEXT,
        created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
        photo TEXT UNIQUE,
        photo_data BYTEA,
        photo_mime TEXT,
        CHECK (
            (photo IS NULL AND photo_data IS NULL AND photo_mime IS NULL) OR
            (photo IS NOT NULL AND photo_data IS NOT NULL AND photo_mime IS NOT NULL)
        )
    )""",
    """CREATE TABLE IF NOT EXISTS report_like (
        report_id BIGINT NOT NULL REFERENCES report(id) ON DELETE CASCADE,
        voter TEXT NOT NULL,
        PRIMARY KEY(report_id, voter)
    )""",
    "CREATE INDEX IF NOT EXISTS idx_report_created ON report(created_at DESC, id DESC)",
    "CREATE INDEX IF NOT EXISTS idx_report_user ON report(user_id)",
)
